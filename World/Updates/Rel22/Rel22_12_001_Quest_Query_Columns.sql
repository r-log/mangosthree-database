-- ----------------------------------------------------------------
-- The quest query reply's columns: quest flags hold 32 bits, and the minimap
-- target mark and reward reputation mask get columns; all take the values of
-- the retail 15595 sniffs, with the reputation overrides.
--
-- The client reads the flags as 32 bits; the column held 24, while 846 quests
-- carry flags in bits 24 to 31 in the sniffs. The values come from the
-- Cataclysm Preservation Project's world database (rows verified on build
-- 15595): flags on 1045 quests, minimap marks on 393, reputation masks on 1299
-- and reputation overrides (RewRepValue1-5, the server's override column) on
-- 1. The new columns are added only where missing, so the update can run
-- again after a failure.
-- ----------------------------------------------------------------
